import { OwnerLocale } from '@zapbip/types';
import { format, resolveConfig } from 'prettier';
import { REFERRAL_SHARING_OPEN } from '../../src/site/site-constants';
import { generatedSubscriberDigestEmail } from './subscriber-digest-template';
import { generatedWelcomeEmailOf } from './welcome-email-template';

export const GENERATED_EMAILS_PATH = new URL('../../src/emails/generated/email-templates.ts', import.meta.url).pathname;

const HEADER = '// NB ADR 0058: generated by pnpm emails:generate from apps/api/scripts/emails; never edit by hand.';
const IMPORTS = [
  "import { OwnerLocale } from '@zapbip/types';",
  "import type { GeneratedDigestEmail, GeneratedEmail } from '../generated-email';",
].join('\n');

function literalOf(value: unknown): string {
  return JSON.stringify(value, null, 2);
}

async function welcomeEntriesOf(): Promise<string[]> {
  return Promise.all(
    Object.entries(OwnerLocale).map(async ([member, locale]) => {
      const email = await generatedWelcomeEmailOf({ locale, isReferralOpen: REFERRAL_SHARING_OPEN });
      return `[OwnerLocale.${member}]: ${literalOf(email)},`;
    }),
  );
}

export async function generatedEmailsSource(): Promise<string> {
  const welcomeEntries = await welcomeEntriesOf();
  const digest = await generatedSubscriberDigestEmail();
  const source = [
    HEADER,
    IMPORTS,
    `export const WELCOME_EMAILS: Record<OwnerLocale, GeneratedEmail> = {\n${welcomeEntries.join('\n')}\n};`,
    `export const SUBSCRIBER_DIGEST_EMAIL: GeneratedDigestEmail = ${literalOf(digest)};`,
  ].join('\n\n');
  const options = await resolveConfig(GENERATED_EMAILS_PATH);
  if (options === null) throw new Error(`no Prettier configuration found for ${GENERATED_EMAILS_PATH}`);
  return format(source, { ...options, filepath: GENERATED_EMAILS_PATH });
}
