import { AgentFacet } from '../src/contract';
import { describe, expect, test } from 'vitest';
import { plugin as fixturePlugin } from '../testing/fixture-plugin-agent/plugin';
import { install as fixtureInstall } from '../testing/fixture-agent/install';
import type { ResolvedAgent } from './agent';
import { renderIds } from './render-ids';
import { realAgents } from './test-agents';

const CONNECTOR_IDS = ['claude-code', 'codex'];
const PLUGIN_IDS = ['hermes', 'openclaw'];
const INSTALL_FREE_IDS = ['any-mcp-client'];
const POINTER_LINE = '// NB ADR 0033: generated by pnpm agents:generate from the agent folders; never edit by hand.';
const MEMBER_PATTERN = /^\s*(\w+) = '([a-z-]+)',?$/;

async function fullFacetAgents(): Promise<ResolvedAgent[]> {
  const agents = await realAgents();
  return agents.map((agent) => ({
    ...agent,
    facets: CONNECTOR_IDS.includes(agent.id) ? [...agent.facets, AgentFacet.Connector] : agent.facets,
    install: INSTALL_FREE_IDS.includes(agent.id) ? null : fixtureInstall,
    plugin: PLUGIN_IDS.includes(agent.id) ? fixturePlugin : null,
  }));
}

function membersOf(input: { source: string; enumName: string }): string[][] {
  const block = input.source.split(`export enum ${input.enumName} {`)[1]?.split('}')[0] ?? '';
  return block
    .split('\n')
    .map((line) => MEMBER_PATTERN.exec(line))
    .flatMap((match) => (match ? [[match[1] as string, match[2] as string]] : []));
}

describe('renderIds', () => {
  test('opens with the pointer to the decision', async () => {
    expect(renderIds({ agents: await fullFacetAgents() }).split('\n')[0]).toBe(POINTER_LINE);
  });

  test('AgentId holds the eleven agents with the member names they have today', async () => {
    const members = membersOf({ source: renderIds({ agents: await fullFacetAgents() }), enumName: 'AgentId' });
    expect(members).toHaveLength(11);
    expect(members).toContainEqual(['ChatGpt', 'chatgpt']);
    expect(members).toContainEqual(['OpenClaw', 'openclaw']);
    expect(members).toContainEqual(['ClaudeAi', 'claude-ai']);
    expect(members).toContainEqual(['AnyMcpClient', 'any-mcp-client']);
  });

  test('InstallClient holds the ten agents with an install facet, in the install page order', async () => {
    const members = membersOf({ source: renderIds({ agents: await fullFacetAgents() }), enumName: 'InstallClient' });
    expect(members.map(([, value]) => value)).toEqual([
      'claude-code',
      'codex',
      'cursor',
      'gemini-cli',
      'grok-bot',
      'claude-ai',
      'chatgpt',
      'grok-web',
      'hermes',
      'openclaw',
    ]);
  });

  test('ConnectorClient holds the agents with a connector facet', async () => {
    const members = membersOf({ source: renderIds({ agents: await fullFacetAgents() }), enumName: 'ConnectorClient' });
    expect(members).toEqual([
      ['ClaudeCode', 'claude-code'],
      ['Codex', 'codex'],
    ]);
  });

  test('PluginAgent holds the agents with a plugin', async () => {
    const members = membersOf({ source: renderIds({ agents: await fullFacetAgents() }), enumName: 'PluginAgent' });
    expect(members).toEqual([
      ['Hermes', 'hermes'],
      ['OpenClaw', 'openclaw'],
    ]);
  });

  test('a registry without a facet is an empty enum', async () => {
    const source = renderIds({ agents: await realAgents() });
    ['InstallClient', 'ConnectorClient', 'PluginAgent'].forEach((enumName) => {
      expect(membersOf({ source, enumName })).toEqual([]);
      expect(source).toContain(`export enum ${enumName} {}`);
    });
  });
});
