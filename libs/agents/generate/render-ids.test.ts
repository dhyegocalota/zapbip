import { describe, expect, test } from 'vitest';
import { renderIds } from './render-ids';
import { fixtureAgents, sampleAgents } from './test-agents';

const POINTER_LINE = '// NB ADR 0033: generated by pnpm agents:generate from the agent folders; never edit by hand.';
const MEMBER_PATTERN = /^\s*(\w+) = '([a-z0-9-]+)',?$/;
const FIXTURE_MEMBERS = [
  ['FixtureAgent', 'fixture-agent'],
  ['FixtureConnectorAgent', 'fixture-connector-agent'],
  ['FixturePluginAgent', 'fixture-plugin-agent'],
];

function membersOf(input: { source: string; enumName: string }): string[][] {
  const afterOpening = input.source.split(`export enum ${input.enumName} {`)[1];
  if (afterOpening === undefined) throw new Error(`no enum ${input.enumName} in the source`);
  const block = afterOpening.split('}')[0] as string;
  return block
    .split('\n')
    .map((line) => MEMBER_PATTERN.exec(line))
    .flatMap((match) => (match ? [[match[1] as string, match[2] as string]] : []));
}

describe('renderIds', () => {
  test('opens with the pointer to the decision', async () => {
    expect(renderIds({ agents: await fixtureAgents() }).split('\n')[0]).toBe(POINTER_LINE);
  });

  test('AgentId holds every agent with the member name its definition declares, by wake rung, then name', async () => {
    const members = membersOf({ source: renderIds({ agents: await fixtureAgents() }), enumName: 'AgentId' });
    expect(members).toEqual(FIXTURE_MEMBERS);
  });

  test('InstallClient holds the agents with an install facet', async () => {
    const agents = (await fixtureAgents()).map((agent) => (agent.id === 'fixture-plugin-agent' ? { ...agent, install: null } : agent));
    const members = membersOf({ source: renderIds({ agents }), enumName: 'InstallClient' });
    expect(members).toEqual(FIXTURE_MEMBERS.slice(0, 2));
  });

  test('ConnectorClient holds the agents with a connector facet', async () => {
    const members = membersOf({ source: renderIds({ agents: await fixtureAgents() }), enumName: 'ConnectorClient' });
    expect(members).toEqual([FIXTURE_MEMBERS[1]]);
  });

  test('PluginAgent holds the agents with a plugin', async () => {
    const members = membersOf({ source: renderIds({ agents: await fixtureAgents() }), enumName: 'PluginAgent' });
    expect(members).toEqual([FIXTURE_MEMBERS[2]]);
  });

  test('a registry without a facet is an empty enum', () => {
    const source = renderIds({ agents: sampleAgents() });
    ['InstallClient', 'ConnectorClient', 'PluginAgent'].forEach((enumName) => {
      expect(membersOf({ source, enumName })).toEqual([]);
      expect(source).toContain(`export enum ${enumName} {}`);
    });
  });
});
